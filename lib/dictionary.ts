type Dict = typeof dictionary;
export type DictKey = { [S in keyof Dict]: `${S}.${string & keyof Dict[S]}` }[keyof Dict];

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const [section, item] = key.split(".") as [keyof Dict, string];
  const entry = (dictionary[section] as Record<string, Record<Locale, string>> | undefined)?.[item];
  let text = entry ? entry[locale] : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}
